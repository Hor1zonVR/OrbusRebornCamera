# RebornCam v0.9.0 Freecam updater.
# Run from the existing OrbusRebornCamera-1 folder.
# Downloads changed source, compiles with the local BepInEx IL2CPP interop,
# and backs up the installed BetterMirror.dll before replacing it.
$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$root = (Get-Location).Path
$source = Join-Path $root "OrbusRebornCamera"
$project = Join-Path $source "BetterMirror.csproj"
if (-not (Test-Path $project)) {
    throw "Run PowerShell inside the OrbusRebornCamera-1 project folder. Not found: $project"
}
if (-not (Get-Command dotnet -ErrorAction SilentlyContinue)) {
    throw ".NET SDK not found. Use the same .NET installation you used to build RebornCam previously."
}
if (Get-Process vrclient,OrbusVR -ErrorAction SilentlyContinue) {
    throw "Close OrbusVR first so its installed DLL can be updated safely."
}

$default = Join-Path $env:USERPROFILE "Downloads\OrbusVR-Reborn-Community-PC-MODTEST\OrbusVR-Reborn-Community-PC"
Write-Host ""
Write-Host "REBORNCAM v0.9.0 - FREECAM + KEYFRAMES" -ForegroundColor Cyan
if (Test-Path (Join-Path $default "BepInEx\interop\UnityEngine.CoreModule.dll")) {
    Write-Host "Default modded test game found:"
    Write-Host $default -ForegroundColor Yellow
    $game = (Read-Host "Press Enter for that folder, or paste a different MODDED Reborn/Renewed game folder").Trim().Trim('"')
    if ([string]::IsNullOrWhiteSpace($game)) { $game = $default }
} else {
    $game = (Read-Host "Paste the full path of your MODDED Reborn/Renewed game folder").Trim().Trim('"')
}
$game = [IO.Path]::GetFullPath($game)

if (-not (Test-Path (Join-Path $game "BepInEx\interop\UnityEngine.CoreModule.dll"))) {
    throw "Game folder must have BepInEx/interop generated by running the modded game at least once."
}
if (-not (Test-Path (Join-Path $game "BepInEx\core\BepInEx.Unity.IL2CPP.dll"))) {
    throw "BepInEx Unity IL2CPP was not found in the selected game folder."
}

$files = @(
    "Plugin.cs",
    "CameraDiagnostics.cs",
    "CameraDiagnostics.Drone.cs",
    "CameraDiagnostics.Panel.cs",
    "CameraDiagnostics.Keyframes.cs",
    "TricksterAssetDiagnostics.cs",
    "TricksterDiskDiagnostics.cs"
)

$backup = Join-Path $env:TEMP ("RebornCam-freecam-source-backup-" + (Get-Date -Format "yyyyMMdd-HHmmss"))
New-Item -ItemType Directory -Force -Path $backup | Out-Null
foreach ($file in $files) {
    $dest = Join-Path $source $file
    if (Test-Path $dest) {
        Copy-Item $dest -Destination (Join-Path $backup $file) -Force
    }
}

$base = "https://raw.githubusercontent.com/Hor1zonVR/OrbusRebornCamera/main/OrbusRebornCamera"
Write-Host "Downloading updated C# files..." -ForegroundColor Cyan
foreach ($file in $files) {
    Invoke-WebRequest -Uri "$base/$file" -OutFile (Join-Path $source $file)
}

Write-Host "Compiling freecam..." -ForegroundColor Cyan
& dotnet build $project --configuration Release "-p:GameDir=$game"
if ($LASTEXITCODE -ne 0) {
    throw "Build failed; the installed RebornCam DLL was NOT replaced. Source backups: $backup"
}
$dll = Join-Path $source "bin\Release\net6.0\BetterMirror.dll"
if (-not (Test-Path $dll)) {
    throw "Build succeeded but BetterMirror.dll not found."
}

$plugins = Join-Path $game "BepInEx\plugins"
New-Item -ItemType Directory -Path $plugins -Force | Out-Null
$existing = @(Get-ChildItem $plugins -Recurse -File -Filter BetterMirror.dll -ErrorAction SilentlyContinue)
if ($existing.Count -gt 1) {
    throw "Multiple BetterMirror.dll copies found. Remove duplicates before installation: $($existing.FullName -join '; ')"
}
$installed = if ($existing.Count -eq 1) { $existing[0].FullName } else { Join-Path $plugins "BetterMirror.dll" }
if (Test-Path $installed) {
    Copy-Item $installed ($installed + ".bak") -Force
}
Copy-Item $dll $installed -Force

Write-Host ""
Write-Host "FREECAM INSTALLED" -ForegroundColor Green
Write-Host "Game: $game"
Write-Host "DLL:  $installed"
Write-Host ""
Write-Host "In game: F2 opens Creator Panel. Choose FREECAM."
Write-Host "Fly: Hold RMB + WASD, Q/E height, Shift speed, Ctrl slow."
Write-Host "Or Ctrl+F11 to toggle; F12 freezes; F2 for cinematic keyframes."
Write-Host "Paths are saved at BepInEx\config\RebornCamKeyframes.txt"
Write-Host "If anything misbehaves, restore BetterMirror.dll.bak."
